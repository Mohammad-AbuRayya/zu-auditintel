        public static AuditItem[] AuditItems() =>
            NumberingCatalog
                .Select((seed, index) => (Seed: seed, SortOrder: index + 1))
                // بنود قالب الكليات موضع ترقيم فقط، لا تُزرع: تُزرع نسخها لكل كلية.
                .Where(row => row.Seed.DepartmentId != FacultyTemplateDepartment)
                .Select(row => new AuditItem
                {
                    Id = row.Seed.Id,
                    DepartmentId = row.Seed.DepartmentId,
                    Category = row.Seed.Category,
                    Title = row.Seed.Title,
                    IsoReference = row.Seed.IsoReference,
                    Workflow = row.Seed.Workflow,
                    SortOrder = row.SortOrder
                }).ToArray();

        /// <summary>
        /// قائمة الفحص الرسمية لا تتضمن عمود أسئلة، فالأسئلة تُشتق من موضوع البند لأن الموضوع نفسه
        /// يتكرر بين الجهات: يُسأل عن الهيكل التنظيمي في المكتبة كما يُسأل عنه في اللوازم.
        /// </summary>
        public static AuditQuestion[] Questions() =>
            Catalog.SelectMany(s => QuestionsFor(s.Title).Select((text, i) => new AuditQuestion
            {
                Id = s.Id * 1000 + i + 1,
                AuditItemId = s.Id,
                Text = text,
                SortOrder = i + 1
            })).ToArray();

        public static AuditEvidenceRequirement[] EvidenceRequirements() =>
            Catalog.SelectMany(item => EvidencesOf(item).Select((text, i) => new AuditEvidenceRequirement
            {
                Id = item.Id * 1000 + 501 + i,
                AuditItemId = item.Id,
                Text = text,
                SortOrder = i + 1
            })).ToArray();

        /// <summary>
        /// أدلة البند من ملف التدقيق الداخلي وحده: قائمة الفحص المعتمدة ZU/QP02F003، نصّها كما ورد
        /// فيها. لا تُحقن هنا أدلة كتاب تعليمات التدقيق الداخلي؛ تُقرأ في ورقة الأدلة عند الحاجة.
        /// </summary>
        private static IEnumerable<string> EvidencesOf(ItemSeed item) =>
            item.Evidences.Distinct(StringComparer.Ordinal);

        private static string[] QuestionsFor(string title) =>
            TopicQuestions
                .FirstOrDefault(topic => topic.Keywords.Any(keyword => title.Contains(keyword, StringComparison.Ordinal)))
                .Questions ?? [];

